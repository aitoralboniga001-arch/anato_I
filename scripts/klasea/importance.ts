/**
 * Writes content/klasea/importance/wN.ts from the rules in lib/klasea/importance.ts.
 * Run: npx tsx scripts/klasea/importance.ts 10
 */
import { writeFileSync } from 'node:fs';
import { getWeek } from '@/content/registry';
import { computeImportance } from '@/lib/klasea/importance';

const n = Number(process.argv[2] ?? 10);
const week = getWeek(n);
if (!week) throw new Error(`No topic ${n}`);
const rows = [...computeImportance(week)].map(([id, v]) => `  '${id}': { tier: '${v.tier}', rules: [${v.rules.map((r) => `'${r}'`).join(', ')}] },`);
const out = `// Generated by scripts/klasea/importance.ts from the rules in lib/klasea/importance.ts. Do not edit.
import type { Importance } from '@/lib/klasea/importance';

export const IMPORTANCE_W${n}: Record<string, Importance> = {
${rows.join('\n')}
};
`;
writeFileSync(`content/klasea/importance/w${n}.ts`, out);
console.log(`w${n}: ${rows.length} sentences ranked`);
