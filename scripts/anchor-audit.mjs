// Leader-dot audit: every name's dot must sit well inside the structure it names (see
// app/dev/frames/Anchors.tsx). Runs /dev/frames?anchors=1 for each week in headless Chrome against a
// running dev server and writes docs/anchor-audit.md.
//
//   node scripts/anchor-audit.mjs [baseUrl=http://localhost:3000] [weeks=1-9]
//
// Set CHROME to the browser binary if it is not in the usual Windows place.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const base = process.argv[2] ?? 'http://localhost:3000';
const [from, to] = (process.argv[3] ?? '1-9').split('-').map(Number);
const chrome =
  process.env.CHROME ??
  ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/usr/bin/google-chrome'].find((p) =>
    existsSync(p),
  );
if (!chrome) throw new Error('Set CHROME to a Chrome/Edge binary');
const profile = join(tmpdir(), `anchor-audit-${process.pid}`);
mkdirSync(profile, { recursive: true });

const KIND = { dot: 'seam / off', span: 'bracket off', 'needs-span': 'needs span', whole: 'whole from one part' };
const decode = (s) => s.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#x27;/g, "'").replace(/&amp;/g, '&');

function page(w, s) {
  try {
    const html = execFileSync(
      chrome,
      ['--headless=new', '--disable-gpu', `--user-data-dir=${profile}`, '--window-size=1100,900', '--virtual-time-budget=300000', '--dump-dom', `${base}/dev/frames?anchors=1&w=${w}${s === undefined ? '' : `&s=${s}`}`],
      { encoding: 'utf8', maxBuffer: 1 << 28, timeout: s === undefined ? 240000 : 90000, stdio: ['ignore', 'pipe', 'ignore'] },
    );
    const pre = /<pre id="anchors"[^>]*>([\s\S]*?)<\/pre>/.exec(html)?.[1];
    const lines = pre ? decode(pre).split('\n').filter(Boolean) : [];
    return lines.at(-1) === 'DONE' ? lines.slice(0, -1).map((l) => JSON.parse(l)) : null;
  } catch {
    return null;
  }
}

/** A week at once; if the page does not finish, stage by stage (a stage that fails is reported as such). */
function run(w) {
  const all = page(w);
  if (all) return all;
  const out = [];
  for (let s = 0; s < 40; s++) {
    const one = page(w, s);
    if (!one?.length) {
      out.push({ stage: `${w}/(stage ${s}: did not finish)`, misses: [], crossed: [], failed: true });
      continue;
    }
    // Past the last stage the page shows the first one again: stop at a repeat.
    if (out.some((o) => o.stage === one[0].stage)) break;
    out.push(...one);
  }
  return out;
}

const out = [
  '# Leader audit: dots, spans and crossings',
  '',
  'Generated by `node scripts/anchor-audit.mjs [baseUrl] [weeks]` (needs the dev server; it reads',
  '`/dev/frames?anchors=1&w=N` in headless Chrome). One week, in the browser: open that URL and read `#anchors`.',
  '',
  '## Rules',
  '',
  '- **Dot (a single structure).** The dot must sit well inside the structure it names, in its thickest part,',
  '  at least 4 frame units from any edge with another structure or the background. Probed: the dot and 8',
  '  points on a 4-unit ring around it must all land on that structure (or a drawing inside it). For a thin',
  '  layer, pick its widest stretch.',
  '- **Span (a layered whole).** A name for a whole made of layers (bilaminar disc = epiblast + hypoblast,',
  '  somatopleure, the amnion, a membrane of 3 layers...) must take in all of them: mark the structure with',
  '  `spans: [first layer, ..., last layer]` in its registry entry, and give its Label a `span`:',
  '',
  '  ```tsx',
  '  <Label id="bi-orriko-diskoa" x={804} y={210} span={[[512, 288], [512, 306]]} />',
  '  ```',
  '',
  '  The two points are the bracket ends: one inside the first layer, one inside the last, across the',
  '  thickness (perpendicular to the layers). The leader meets the bracket’s middle (ax/ay default to it),',
  '  and the bracket replaces the dot. `spans` also lights every layer when the name is pointed at or is a',
  '  step’s focus (it stands in for `parts` when that is unset). Probed: 9 points along the bracket; the first',
  '  must land on the first layer, the last on the last layer (either way round), all of them on the whole.',
  '- **Whole from one part.** A whole with `parts` named with a dot inside just one of its parts is listed',
  '  too: if the parts are layers, give it `spans` and a span; if not, point at the part that best stands',
  '  for it, or name the parts.',
  '- **Crossings.** Leaders that still cross after the label layer has re-seated the names (see',
  '  components/kit/columns.tsx). Fix them at the source: reorder the scene’s slots. A name the layer must',
  '  not move takes `<Label noArrange>`; a whole scene, `MyScene.noArrange = true`. In `/dev/frames` a name',
  '  the layer moved has a yellow plate outline.',
  '',
  'Every view of every stage is checked at each step’s finished frame. Problem kinds: `seam / off` (dot',
  'or its ring off the structure; **dot off** = the dot itself), `bracket off`, `needs span`, `whole from',
  'one part`. `(hondoa)` = background.',
  '',
];
let total = 0;
let crossTotal = 0;
for (let w = from; w <= to; w++) {
  const stages = run(w);
  const rows = [];
  for (const { stage, misses } of stages) {
    // One row per name and place, with the steps it shows in.
    const by = new Map();
    for (const m of misses) {
      const k = `${m.view}|${m.id}|${m.kind}|${m.at}`;
      const r = by.get(k) ?? { ...m, steps: [] };
      r.steps.push(m.step);
      r.off = Math.max(r.off, m.off);
      r.centre ||= m.centre;
      r.on = [...new Set([...r.on, ...m.on])];
      by.set(k, r);
    }
    for (const r of by.values())
      rows.push(`| ${stage.split('/')[1]} / ${r.view} | ${r.steps.join(',')} | ${r.id} | ${KIND[r.kind]} | ${r.at.join(',')} | ${r.kind === 'needs-span' ? '' : `${r.off}/9`}${r.centre && r.kind === 'dot' ? ' **dot off**' : ''} | ${r.on.join(', ')} |`);
  }
  // Leader crossings the label layer could not remove: fix these at the source (the scene’s slots).
  const xs = new Map();
  for (const { stage, crossed = [] } of stages)
    for (const c of crossed) {
      const k = `${stage.split('/')[1]} / ${c.view}|${c.a} × ${c.b}`;
      xs.set(k, [...(xs.get(k) ?? []), c.step]);
    }
  const xrows = [...xs].map(([k, steps]) => `| ${k.split('|')[0]} | ${steps.join(',')} | ${k.split('|')[1]} |`);
  total += rows.length;
  crossTotal += xrows.length;
  out.push(`## Week ${w}`, '');
  const failed = stages.filter((x) => x.failed).map((x) => x.stage.split('/')[1]);
  if (failed.length) out.push(`Could not audit (the page did not finish): ${failed.join(', ')}.`, '');
  out.push(`### Dots (${rows.length})`, '');
  if (rows.length) out.push('| stage / view | steps | name | problem | at | off | lands on |', '|---|---|---|---|---|---|---|', ...rows, '');
  else out.push('All dots clear.', '');
  out.push(`### Leader crossings left after the label layer (${xrows.length})`, '');
  if (xrows.length) out.push('| stage / view | steps | names |', '|---|---|---|', ...xrows, '');
  else out.push('None.', '');
  console.log(`week ${w}: ${rows.length} dots, ${xrows.length} crossings`);
}
out.splice(2, 0, `Total: ${total} dot placements off their structure; ${crossTotal} leader crossings left.`, '');
writeFileSync('docs/anchor-audit.md', out.join('\n'));
console.log('wrote docs/anchor-audit.md');
